"""Emit shared theme tokens and standalone-page copies from canonical sources."""
from pathlib import Path
import json
import argparse

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'development/design-system'


def outputs():
    tokens=json.loads((SOURCE/'tokens.json').read_text(encoding='utf-8'))
    def declarations(values):
        return '\n'.join(f'  --hk-{name}: {value};' for name,value in values.items())
    css='/* Generated by scripts/sync_design_system.py; edit tokens.json. */\n'
    css+=':root {\n'+declarations(tokens['shared'])+'\n}\n'
    for mode,values in tokens['themes'].items():
        selector=':root, [data-theme="light"]' if mode=='light' else '[data-theme="dark"]'
        css+=f'{selector} {{\n  color-scheme: {mode};\n'+declarations(values)+'\n}\n'
    css+='@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n'+declarations(tokens['themes']['dark'])+'\n  color-scheme: dark;\n  }\n}\n'
    css+='@media (prefers-contrast: more) {\n  :root { --hk-separator: var(--hk-control-border); --hk-text-tertiary: var(--hk-text-secondary); }\n}\n'
    css+='@media (prefers-reduced-motion: reduce) { :root { --hk-duration: 0ms; } }\n'
    result={SOURCE/'tokens.css':css}
    components=(SOURCE/'components.css').read_text(encoding='utf-8')
    controller=(SOURCE/'appearance.js').read_text(encoding='utf-8')
    for directory in [ROOT/'docs/prototypes',ROOT/'docs/prototypes/tasks',ROOT/'docs/design/system']:
        result[directory/'design-tokens.css']=css
        result[directory/'design-components.css']=components
        result[directory/'appearance.js']=controller
    result[ROOT/'development/apps/desktop/public/appearance.js']=controller
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    mismatches=[]
    for path,content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8')!=content:mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content,encoding='utf-8')
    if mismatches:raise SystemExit('Design system copies out of sync: '+', '.join(mismatches))
    print('Design system sources synchronized' if not args.check else 'Design system copies verified')
